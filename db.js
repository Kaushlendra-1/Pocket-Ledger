/*
  db.js
  --------------------------------------------------------
  A small wrapper around IndexedDB so the rest of the app
  never has to deal with raw IndexedDB callbacks directly.

  Every function returns a Promise, so you can use
  async/await in app.js.

  A "transaction" record looks like:
  {
    id: 1,                 // auto-generated by IndexedDB
    type: "expense",       // "expense" | "income"
    amount: 250,
    category: "Grocery",
    note: "Weekly veggies",
    paymentMethod: "cash", // "cash" | "online"
    date: "2026-06-13",    // ISO format (YYYY-MM-DD)
    createdAt: 1718270000000 // Date.now() timestamp
  }
--------------------------------------------------------- */

const DB_NAME = "pocketLedgerDB";
const DB_VERSION = 2;
const STORE_NAME = "transactions";
const CATEGORY_STORE_NAME = "categories";

// Seeded into the "categories" store the first time the database
// is created (or upgraded from version 1).
const DEFAULT_CATEGORIES = {
  expense: ["Grocery", "Food", "Travel", "Bills", "Rent", "Entertainment", "Shopping", "Health", "Other"],
  income: ["Salary", "Freelance", "Gift", "Interest", "Other"],
};

let dbInstance = null;

/**
 * Opens (or creates) the database and the object store.
 * Subsequent calls reuse the same open connection.
 */
function openDB() {
  return new Promise((resolve, reject) => {
    if (dbInstance) {
      resolve(dbInstance);
      return;
    }

    const request = indexedDB.open(DB_NAME, DB_VERSION);

    // Runs only the first time, or when DB_VERSION is increased.
    // This is where we define the "shape" of the database.
    request.onupgradeneeded = (event) => {
      const db = event.target.result;

      if (!db.objectStoreNames.contains(STORE_NAME)) {
        const store = db.createObjectStore(STORE_NAME, {
          keyPath: "id",
          autoIncrement: true,
        });

        // Indexes let us query/filter quickly later
        // (e.g. "all transactions on this date" or "all expenses").
        store.createIndex("date", "date", { unique: false });
        store.createIndex("type", "type", { unique: false });
        store.createIndex("category", "category", { unique: false });
      }

      if (!db.objectStoreNames.contains(CATEGORY_STORE_NAME)) {
        const catStore = db.createObjectStore(CATEGORY_STORE_NAME, {
          keyPath: "id",
          autoIncrement: true,
        });
        catStore.createIndex("type", "type", { unique: false });

        // Seed with the default category lists so the dropdowns
        // aren't empty on first run.
        const tx = event.target.transaction;
        const seedStore = tx.objectStore(CATEGORY_STORE_NAME);
        Object.entries(DEFAULT_CATEGORIES).forEach(([type, names]) => {
          names.forEach((name) => seedStore.add({ type, name }));
        });
      }
    };

    request.onsuccess = (event) => {
      dbInstance = event.target.result;
      resolve(dbInstance);
    };

    request.onerror = (event) => {
      reject(event.target.error);
    };
  });
}

/**
 * Adds a new transaction. Returns the new record's id.
 */
async function addTransaction(transaction) {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(STORE_NAME, "readwrite");
    const store = tx.objectStore(STORE_NAME);
    const request = store.add(transaction);

    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}

/**
 * Returns every transaction in the database as an array.
 */
async function getAllTransactions() {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(STORE_NAME, "readonly");
    const store = tx.objectStore(STORE_NAME);
    const request = store.getAll();

    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}

/**
 * Updates an existing transaction (must include its id).
 */
async function updateTransaction(transaction) {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(STORE_NAME, "readwrite");
    const store = tx.objectStore(STORE_NAME);
    const request = store.put(transaction);

    request.onsuccess = () => resolve();
    request.onerror = () => reject(request.error);
  });
}

/**
 * Deletes a transaction by id.
 */
async function deleteTransaction(id) {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(STORE_NAME, "readwrite");
    const store = tx.objectStore(STORE_NAME);
    const request = store.delete(id);

    request.onsuccess = () => resolve();
    request.onerror = () => reject(request.error);
  });
}

/**
 * Deletes ALL transactions. Used when restoring a backup
 * (the imported data replaces everything currently stored).
 */
async function clearAllTransactions() {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(STORE_NAME, "readwrite");
    const store = tx.objectStore(STORE_NAME);
    const request = store.clear();

    request.onsuccess = () => resolve();
    request.onerror = () => reject(request.error);
  });
}

/**
 * Returns the category names for a given type ("expense" | "income"),
 * including any custom categories the user has added.
 */
async function getCategories(type) {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(CATEGORY_STORE_NAME, "readonly");
    const store = tx.objectStore(CATEGORY_STORE_NAME);
    const index = store.index("type");
    const request = index.getAll(type);

    request.onsuccess = () => resolve(request.result.map((row) => row.name));
    request.onerror = () => reject(request.error);
  });
}

/**
 * Adds a new custom category for a given type.
 */
async function addCategory(type, name) {
  const db = await openDB();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(CATEGORY_STORE_NAME, "readwrite");
    const store = tx.objectStore(CATEGORY_STORE_NAME);
    const request = store.add({ type, name });

    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}